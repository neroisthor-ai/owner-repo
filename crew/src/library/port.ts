// Port the three single-file films into modern ES modules ("film kits").
//
// Each kit is generated from the verbatim film source in library/reference/,
// with a short, explicit list of edits (every edit must match exactly or the
// port fails): inject the renderer/canvas/container, route the film's own UI to
// inert elements, swap three.js r128/r147 APIs for current ones, and load data
// from the library instead of embedded blobs. Everything else is the film's own
// code, so the kits render what the films rendered, and expose every builder.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Edit = [find: string | RegExp, replace: string, note?: string];

function applyEdits(src: string, edits: Edit[], film: string): string {
  let s = src;
  for (const [find, rep, note] of edits) {
    if (typeof find === "string") {
      if (!s.includes(find)) throw new Error(`${film}: edit did not match (${note ?? find.slice(0, 80)})`);
      s = s.split(find).join(rep);
    } else {
      find.lastIndex = 0;
      if (!find.test(s)) throw new Error(`${film}: regex edit did not match (${note ?? String(find)})`);
      s = s.replace(find, rep);
    }
  }
  return s;
}

/** Only export names the film actually defines. */
function exportsFor(src: string, names: string[]) {
  return names.filter((n) => new RegExp(`(?:function\\*?|const|let|var|class)\\s+${n.replace("$", "\\$")}\\b`).test(src));
}

function header(film: string, from: string) {
  return `// GENERATED by \`crew library port\` from ${from}. Do not edit by hand: change src/library/port.ts and re-run.
// ${film}, ported to current three.js. The film's own code, with the edits listed in src/library/port.ts.
`;
}

