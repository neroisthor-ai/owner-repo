  const names = exportsFor(body, ["DUR", "SHOTS", "CUTS", "stateAt", "renderFrame", "shotIndex", "shotCam", "simAt", "shipAt", "scyllaAt", "lightningAt", "resize", "fit", "setPlay", "loop", "master", "audioStart", "audioStop", "pickVideoConfig", "pickAudioConfig", "timecode"]);
